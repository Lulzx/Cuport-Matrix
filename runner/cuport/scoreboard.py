"""Generate the Markdown scoreboard (docs/scoreboard.md) from committed result rows.

For every (tool, hardware) pair the latest results/<tool>/<hardware>/<date>.json
is used. A probe missing from a row counts as not-run. The hosted-vs-M6
disagreement rate is the share of probes, among those classified on both lanes
for the same tool, whose class differs between `paravirtual` and `m6-12c`.
"""

from __future__ import annotations

import collections
import json
import pathlib
from dataclasses import dataclass

from cuport.rows import CLASSES

HOSTED, M6 = "paravirtual", "m6-12c"
LANE_ORDER = (M6, HOSTED)
TOOL_ORDER = ("mvcc", "cumetal")
V0_TOOLS = ("mvcc", "cumetal")
V0_LANES = (M6, HOSTED)

SHORT = {
    "bit-exact": "exact",
    "within-tolerance": "tol",
    "documented-divergence": "doc-div",
    "undocumented-divergence": "**UNDOC**",
    "refused-with-diagnostic": "refused",
    "silently-wrong": "**WRONG**",
    "crash-hang": "**crash**",
    "not-run": "·",
}


@dataclass(frozen=True)
class Row:
    tool: str
    version: str
    hardware: str
    date: str
    path: pathlib.Path
    repo_commit: str
    classes: dict  # probe id -> class
    upstream: dict  # probe id -> upstream link or None


def _sort_key(pair):
    tool, hw = pair
    t = TOOL_ORDER.index(tool) if tool in TOOL_ORDER else len(TOOL_ORDER)
    h = LANE_ORDER.index(hw) if hw in LANE_ORDER else len(LANE_ORDER)
    return (t, tool, h, hw)


def latest_rows(results: pathlib.Path) -> list[Row]:
    """The newest row for each (tool, hardware) under results/, in display order."""
    newest: dict[tuple[str, str], pathlib.Path] = {}
    for f in sorted(results.glob("*/*/*.json")):
        key = (f.parent.parent.name, f.parent.name)
        if key not in newest or f.stem > newest[key].stem:
            newest[key] = f
    rows = []
    for key in sorted(newest, key=_sort_key):
        data = json.loads(newest[key].read_text())
        classes, upstream = {}, {}
        for c in data["cells"]:
            classes.setdefault(c["probe"], c["class"])
            upstream.setdefault(c["probe"], c.get("upstream"))
        commit = (data.get("runner", {}).get("config", {}) or {}).get("repo_commit", "")
        rows.append(Row(data["tool"]["id"], data["tool"]["version"], data["hardware"]["id"], data["date"],
                        newest[key], commit, classes, upstream))
    return rows


@dataclass(frozen=True)
class Disagreement:
    tool: str
    compared: int
    differ: list  # (probe, hosted class, m6 class)

    @property
    def rate(self) -> float | None:
        return len(self.differ) / self.compared if self.compared else None


def disagreement(rows: list[Row]) -> list[Disagreement]:
    by = {(r.tool, r.hardware): r for r in rows}
    out = []
    for tool in sorted({r.tool for r in rows}, key=lambda t: _sort_key((t, ""))):
        h, m = by.get((tool, HOSTED)), by.get((tool, M6))
        if not h or not m:
            continue
        both = sorted(p for p in set(h.classes) & set(m.classes)
                      if h.classes[p] != "not-run" and m.classes[p] != "not-run")
        differ = [(p, h.classes[p], m.classes[p]) for p in both if h.classes[p] != m.classes[p]]
        out.append(Disagreement(tool, len(both), differ))
    return out


def _pct(n: int, d: int) -> str:
    return f"{100 * n / d:.1f} %" if d else "n/a"


def render(rows: list[Row], probe_ids: list[str], drops: dict[str, list[str]], root: pathlib.Path) -> str:
    """drops: probe id -> NVIDIA reference-drop tags present for it."""
    L: list[str] = []
    w = L.append
    w("# Scoreboard")
    w("")
    w("Generated by `PYTHONPATH=runner python -m cuport scoreboard` from the newest")
    w("row per tool and hardware under `results/`. Do not edit by hand; CI fails when")
    w("this file is stale. Classes are defined in `matrix/schema.md`; every")
    w("divergence is explained in `docs/divergences.md`.")
    w("")

    # ---- summary -----------------------------------------------------------
    w("## Rows")
    w("")
    head = ["Tool", "Hardware", "Date", "Repo commit", *CLASSES]
    w("| " + " | ".join(head) + " |")
    w("|" + "|".join(["---"] * 4 + ["--:"] * len(CLASSES)) + "|")
    for r in rows:
        counts = collections.Counter(r.classes.get(p, "not-run") for p in probe_ids)
        rel = r.path.relative_to(root).as_posix()
        w(f"| {r.tool} {r.version} | `{r.hardware}` | [{r.date}]({'../' + rel}) | `{r.repo_commit[:7]}` | "
          + " | ".join(str(counts.get(c, 0)) for c in CLASSES) + " |")
    w("")

    # ---- v0 criteria ---------------------------------------------------------
    by = {(r.tool, r.hardware): r for r in rows}
    target = len(probe_ids) * len(V0_TOOLS) * len(V0_LANES)
    classified = sum(1 for t in V0_TOOLS for h in V0_LANES for p in probe_ids
                     if (t, h) in by and by[(t, h)].classes.get(p, "not-run") != "not-run")
    acknowledged = sorted({r.upstream[p] for r in rows for p in r.classes
                           if r.classes[p] == "undocumented-divergence" and r.upstream.get(p)})
    w("## Milestone v0 criteria")
    w("")
    w("| Criterion | Target | Now |")
    w("|---|---|---|")
    w(f"| Cells classified (not `not-run`) | at least 90 % of {len(probe_ids)} probes x "
      f"{len(V0_TOOLS)} tools x {len(V0_LANES)} lanes = {target} | {classified} of {target} "
      f"({_pct(classified, target)}) |")
    w(f"| Undocumented divergences acknowledged upstream | at least 3 | {len(acknowledged)} issues |")
    dis = disagreement(rows)
    pooled_c = sum(d.compared for d in dis)
    pooled_d = sum(len(d.differ) for d in dis)
    now = (f"{pooled_d} of {pooled_c} probes ({_pct(pooled_d, pooled_c)})" if pooled_c
           else "not measured: no `paravirtual` row yet")
    w(f"| Hosted-vs-M6 disagreement rate | reported as a number | {now} |")
    w("")

    # ---- disagreement ------------------------------------------------------
    w("## Hosted-vs-M6 disagreement")
    w("")
    w(f"Share of probes, classified on both `{HOSTED}` and `{M6}` for the same tool,")
    w("whose class differs between the two lanes. The paravirtual GPU is a feature")
    w("subset of real Apple silicon, so a difference is a lane artefact until shown")
    w("otherwise; it is never folded into the M6 result.")
    w("")
    if not dis:
        w(f"Not measured yet: no tool has both a `{HOSTED}` and a `{M6}` row.")
    else:
        w("| Tool | Compared | Differ | Rate |")
        w("|---|--:|--:|--:|")
        for d in dis:
            w(f"| {d.tool} | {d.compared} | {len(d.differ)} | {_pct(len(d.differ), d.compared)} |")
        w(f"| **all** | {pooled_c} | {pooled_d} | **{_pct(pooled_d, pooled_c)}** |")
        diffs = [(d.tool, *x) for d in dis for x in d.differ]
        if diffs:
            w("")
            w(f"| Tool | Probe | `{HOSTED}` | `{M6}` |")
            w("|---|---|---|---|")
            for tool, p, hc, mc in diffs:
                w(f"| {tool} | `{p}` | {hc} | {mc} |")
    w("")

    # ---- per-probe matrix ----------------------------------------------------
    w("## Probe matrix")
    w("")
    w("Legend: " + ", ".join(f"{v} = {k}" for k, v in SHORT.items()) + ".")
    w("The NVIDIA column lists the stock-`nvcc` reference drops committed for the")
    w("probe (`probes/<family>/<id>/reference/`); every drop matches the probe's oracle.")
    w("")
    cols = [f"{r.tool} `{r.hardware}`" for r in rows]
    w("| Probe | " + " | ".join(cols) + " | NVIDIA |")
    w("|---|" + "|".join([":-:"] * len(cols)) + "|---|")
    family = None
    for p in probe_ids:
        fam = p.split("/")[0]
        if fam != family:
            family = fam
            w(f"| **{fam}** |" + " |" * len(cols) + " |")
        cells = [SHORT[r.classes.get(p, "not-run")] for r in rows]
        w(f"| `{p.split('/')[1]}` | " + " | ".join(cells) + f" | {', '.join(drops.get(p, [])) or '·'} |")
    w("")

    # ---- upstream ------------------------------------------------------------
    w("## Upstream issues")
    w("")
    issues = sorted({(r.tool, p, r.upstream[p]) for r in rows for p in r.classes
                     if r.classes[p] == "undocumented-divergence" and r.upstream.get(p)})
    if not issues:
        w("None yet.")
    for tool, p, link in issues:
        lanes = ", ".join(f"`{r.hardware}`" for r in rows
                          if r.tool == tool and r.classes.get(p) == "undocumented-divergence")
        w(f"- {tool}, `{p}` ({lanes}): {link}")
    w("")
    return "\n".join(L)


def build(root: pathlib.Path, probe_ids: list[str]) -> str:
    drops = {}
    for p in probe_ids:
        ref = root / "probes" / p / "reference"
        drops[p] = sorted(d.name for d in ref.iterdir() if d.is_dir()) if ref.is_dir() else []
    return render(latest_rows(root / "results"), probe_ids, drops, root)
